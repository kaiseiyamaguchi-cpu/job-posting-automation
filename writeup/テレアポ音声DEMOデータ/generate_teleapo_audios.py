def speedup_with_ffmpeg(src: Path, dst: Path, speed: float) -> bool:
    """
    ffmpegのatempoフィルタで速度変更。atempoは0.5〜2.0のため、2.0と残差で連結。
    例: 3.0倍なら atempo=2.0,atempo=1.5
    """
    if shutil.which("ffmpeg") is None:
        return False
    # 分解してフィルタ連結を作る
    factors = []
    remaining = speed
    while remaining > 2.0:
        factors.append(2.0)
        remaining /= 2.0
    if remaining < 0.5:
        remaining = 0.5
    factors.append(remaining)
    filter_str = ",".join([f"atempo={f:.6g}" for f in factors])
    cmd = [
        "ffmpeg", "-y",
        "-i", str(src),
        "-filter:a", filter_str,
        "-vn",
        str(dst),
    ]
    try:
        subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        return True
    except subprocess.CalledProcessError:
        return False


def main() -> None:
    output_dir = Path(__file__).parent / "output_audio"
    os.makedirs(output_dir, exist_ok=True)

    dialogues = get_dialogues()

    for idx, text in enumerate(dialogues, start=1):
        file_name = f"teleapo_{idx:02d}.mp3"
        target_path = output_dir / file_name

        # まず一旦通常速度で生成
        tmp_path = output_dir / f"tmp_{idx:02d}.mp3"
        tts = gTTS(text=text, lang="ja", slow=False)
        tts.save(str(tmp_path))

        # 2倍速に変換（ffmpegがあれば）
        ok = speedup_with_ffmpeg(tmp_path, target_path, speed=2.0)
        if not ok:
            # 失敗時は通常速度をそのまま採用
            os.replace(tmp_path, target_path)
        else:
            try:
                os.remove(tmp_path)
            except FileNotFoundError:
                pass

        print(f"Saved: {target_path}")

    print("完了: 10個のデモ音声を 'output_audio' フォルダに生成しました。")


if __name__ == "__main__":
    main()


